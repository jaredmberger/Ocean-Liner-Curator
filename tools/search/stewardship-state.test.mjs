import assert from 'node:assert/strict';
import { reconcile } from './stewardship-state.mjs';
const now='2026-10-16T00:00:00Z';
const item={id:'one',type:'canonical:canonical-route-not-found',scope:'page',evidence:{canonical:'/bad'}};
const first=reconcile(null,[item],now,['canonical','internal-links']);
assert.deepEqual(first.changes.new,['one']);
assert.equal(first.cases[0].firstSeen,now);
const later='2026-10-17T00:00:00Z';
const continuing=reconcile(first,[item],later,['canonical','internal-links']);
assert.deepEqual(continuing.changes.continuing,['one']);
assert.equal(continuing.cases[0].occurrences,2);
const missingAudit=reconcile(continuing,[],later,['internal-links']);
assert.deepEqual(missingAudit.changes.unverified,['one']);
assert.equal(missingAudit.cases[0].lifecycle,'unverified');
const resolved=reconcile(continuing,[],later,['canonical']);
assert.deepEqual(resolved.changes.resolved,['one']);
const repeat=reconcile(resolved,[],later,['canonical']);
assert.equal(repeat.changes.resolved.length,0);
assert.equal(repeat.cases[0].firstSeen,now);
console.log('Stewardship lifecycle tests passed.');
